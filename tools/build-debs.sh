#!/bin/bash
# =============================================================================
# tools/build-debs.sh — build the seven NimbusOS .deb packages
# =============================================================================
# What: for each package in packages/, stages a self-contained copy in
#       _build/src/<package>/ together with what it needs from elsewhere in
#       the repository:
#         nimbusos-archive-keyring  the committed NimbusOS public keys
#         nimbusos-docker-keyring   Docker's key (build/config/archives/)
#         nimbus-control            control-center/
#         nimbus-catalog            catalog/
#         nimbusos-desktop          its Depends, generated from the package
#                                   lists by tools/gen-desktop-depends.sh
#       It then writes the build values (nimbus-build.env, debian/nimbus-build.mk),
#       adds a debian/changelog entry for the version from git, and runs
#       dpkg-buildpackage. Finally it checks that the seven .debs share one
#       version, that the archive keyring trusts exactly the committed keys,
#       and that the Docker keyring holds exactly Docker's key.
#
# Why:  one build path for build/build.sh, ci.yml and release.yml, so the ISO
#       and the APT repository always contain the same packages (ground
#       rule 2). The checked-in tree is never modified (docs/PLAN.md NOTE-47).
#
# Usage: tools/build-debs.sh [options]
#   --out DIR             where to put the .deb files (default: NIMBUS_DEBS_DIR
#                         from build/nimbus.conf)
#   --tag TAG             build release tag TAG (CI passes GITHUB_REF_NAME)
#   --install-build-deps  install host tools and each package's Build-Depends
#                         with apt (needs root)
#   --lintian             run lintian on the built .debs; any error or warning
#                         fails the build (overrides live in each package)
#   --allow-test-key      if no archive key is committed yet, generate a
#                         throwaway key so CI can build (docs/PLAN.md NOTE-44).
#                         Packages built this way must never be published or
#                         put into an image; build.sh and release.yml refuse them.
#   --only PKG[,PKG...]   build only these packages (development and tests).
#                         The seven-package set check is skipped, so the
#                         result must never be published; release.yml and
#                         build.sh never pass it.
#   -h, --help            show this help
# =============================================================================
set -Eeuo pipefail

# shellcheck source=build/lib/common.sh
. "$(dirname "$(readlink -f "$0")")/../build/lib/common.sh"

usage() {
	sed -n '/^# Usage:/,/^# =====/p' "$0" | sed -e '$d' -e 's/^# \{0,1\}//'
}

opt_out=""
opt_tag=""
opt_build_deps=""
opt_lintian=""
opt_allow_test_key=""
opt_only=""
NIMBUS_TEST_KEY=""      # "1" when a throwaway key was generated (recorded in nimbus-build.env)
staging=""
test_key_file=""

# -----------------------------------------------------------------------------
# Build values for the packaging (docs/PLAN.md NOTE-49)
# -----------------------------------------------------------------------------
# Every NIMBUS_* setting plus the version values, as a shell file (for
# maintainer tooling and tests) and as a make fragment (included by
# debian/rules, which substitutes @NIMBUS_*@ tokens in templates).
write_build_values() {
	local dst="$1" var val
	local -a vars=()
	for var in $(compgen -v NIMBUS_); do
		case "$var" in
			NIMBUS_REPO_ROOT|NIMBUS_GNUPGHOME|NIMBUS_PACKAGES|NIMBUS_LB_ARGS|NIMBUS_CONF) continue ;;
		esac
		vars+=("$var")
	done
	vars+=(SOURCE_DATE_EPOCH)

	{
		printf '# Generated by tools/build-debs.sh: build values for this package.\n'
		for var in "${vars[@]}"; do
			printf '%s=%q\n' "$var" "${!var}"
		done
	} >"$dst/nimbus-build.env"

	{
		printf '# Generated by tools/build-debs.sh: included by debian/rules.\n'
		for var in "${vars[@]}"; do
			val="${!var}"
			val="${val//\$/\$\$}"          # make: a literal $ is written $$
			val="${val//\#/\\#}"           # make: # would start a comment
			printf 'export %s := %s\n' "$var" "$val"
		done
	} >"$dst/debian/nimbus-build.mk"
}

# -----------------------------------------------------------------------------
# debian/changelog: add an entry for the version being built
# -----------------------------------------------------------------------------
# The committed changelog holds the package's history. If its newest entry is
# already the version being built, it is used as written; otherwise a new
# entry is added on top. The date is the commit time, so rebuilding the same
# commit gives byte-identical packages.
update_changelog() {
	local dst="$1" pkg="$2" cl="$1/debian/changelog" top date
	[[ -s "$cl" ]] || die "packages/$pkg/debian/changelog is missing."
	top="$(dpkg-parsechangelog -l "$cl" -S Version)"
	if [[ "$top" == "$NIMBUS_VERSION" ]]; then
		log "$pkg: debian/changelog already has $NIMBUS_VERSION; using that entry."
		return 0
	fi
	if dpkg --compare-versions "$top" gt "$NIMBUS_VERSION"; then
		die "$pkg: the newest debian/changelog entry ($top) is newer than the version being built ($NIMBUS_VERSION). Tag the release first, or remove that entry."
	fi
	date="$(LC_ALL=C date -u -R -d "@${SOURCE_DATE_EPOCH}")"
	{
		printf '%s (%s) %s; urgency=medium\n\n' "$pkg" "$NIMBUS_VERSION" "$NIMBUS_SUITE"
		if [[ "$NIMBUS_CHANNEL" == dev ]]; then
			printf '  * Development build of %s from git commit %s.\n' "$NIMBUS_NAME" "$NIMBUS_GIT_COMMIT"
		else
			printf '  * %s %s (%s channel), git commit %s.\n' \
				"$NIMBUS_NAME" "$NIMBUS_DISPLAY_VERSION" "$NIMBUS_CHANNEL" "$NIMBUS_GIT_COMMIT"
			printf '    Release notes:\n    %s/releases/tag/%s\n' "$NIMBUS_HOME_URL" "$NIMBUS_TAG"
		fi
		printf '\n -- %s  %s\n\n' "$NIMBUS_MAINTAINER" "$date"
		cat "$cl"
	} >"$cl.new"
	mv -f -- "$cl.new" "$cl"
	[[ "$(dpkg-parsechangelog -l "$cl" -S Version)" == "$NIMBUS_VERSION" ]] \
		|| die "$pkg: could not write the debian/changelog entry for $NIMBUS_VERSION."
}

# -----------------------------------------------------------------------------
# Throwaway archive key (CI only, before the real key is committed)
# -----------------------------------------------------------------------------
make_test_key() {
	local tmp
	nimbus_mktemp_dir tmp
	warn "No NimbusOS archive key is committed in $NIMBUS_ARCHIVE_KEYS_DIR/."
	warn "Generating a THROWAWAY key. These packages must never be published or put into an image."
	GNUPGHOME="$NIMBUS_GNUPGHOME" gpg --batch --quiet --pinentry-mode loopback --passphrase '' \
		--quick-gen-key "NimbusOS CI throwaway key <nimbusos-ci-throwaway@invalid>" ed25519 sign 1d
	GNUPGHOME="$NIMBUS_GNUPGHOME" gpg --batch --quiet --armor \
		--export "nimbusos-ci-throwaway@invalid" >"$tmp/nimbusos-ci-throwaway.asc"
	GNUPGHOME="$NIMBUS_GNUPGHOME" gpgconf --kill gpg-agent || true
	test_key_file="$tmp/nimbusos-ci-throwaway.asc"
	NIMBUS_TEST_KEY=1
}

# -----------------------------------------------------------------------------
# Staging
# -----------------------------------------------------------------------------
stage_package() {
	local pkg="$1" src dst
	src="$NIMBUS_REPO_ROOT/packages/$pkg"
	dst="$staging/$pkg"
	[[ -f "$src/debian/control" ]] || die "packages/$pkg/debian/control is missing; cannot build $pkg."

	rm -rf -- "$dst"
	mkdir -p -- "$dst"
	cp -a -- "$src/." "$dst/"

	case "$pkg" in
		nimbusos-archive-keyring)
			# keys/*.asc came with the copy above; add the throwaway key if
			# one was generated.
			mkdir -p -- "$dst/keys"
			if [[ -n "$test_key_file" ]]; then
				install -m 0644 -- "$test_key_file" "$dst/keys/"
			fi
			;;
		nimbusos-docker-keyring)
			# Docker's key, already fingerprint-checked by nimbus_check_docker_key.
			# The canonical copy is the one live-build uses during the build.
			install -m 0644 -- "$(nimbus_path "$NIMBUS_DOCKER_KEY_FILE")" "$dst/docker-archive-keyring.asc"
			;;
		nimbus-control)
			[[ -d "$NIMBUS_REPO_ROOT/control-center" ]] || die "control-center/ is missing; cannot build nimbus-control."
			cp -a -- "$NIMBUS_REPO_ROOT/control-center" "$dst/control-center"
			;;
		nimbus-catalog)
			[[ -d "$NIMBUS_REPO_ROOT/catalog" ]] || die "catalog/ is missing; cannot build nimbus-catalog."
			cp -a -- "$NIMBUS_REPO_ROOT/catalog" "$dst/catalog"
			;;
		nimbusos-desktop)
			# ${nimbus:ListDepends} and ${nimbus:ListRecommends}, generated from
			# the live-build package lists so the image and the metapackage
			# never drift (NOTE-48).
			"$NIMBUS_REPO_ROOT/tools/gen-desktop-depends.sh" --depends >"$dst/debian/nimbus-list-depends"
			"$NIMBUS_REPO_ROOT/tools/gen-desktop-depends.sh" --recommends >"$dst/debian/nimbus-list-recommends"
			[[ -s "$dst/debian/nimbus-list-depends" && -s "$dst/debian/nimbus-list-recommends" ]] \
				|| die "tools/gen-desktop-depends.sh produced an empty Depends or Recommends list."
			;;
	esac

	write_build_values "$dst"
	# File modes as recorded in git, not as the host file system shows them
	# (see common.sh). The package tree first, then the copied source trees.
	nimbus_apply_git_modes "$dst" "packages/$pkg"
	case "$pkg" in
		nimbus-control) nimbus_apply_git_modes "$dst/control-center" "control-center" ;;
		nimbus-catalog) nimbus_apply_git_modes "$dst/catalog" "catalog" ;;
	esac
	# Fill in @NIMBUS_*@ tokens everywhere in the staged copy: debian/control
	# (Maintainer, Homepage), debian/changelog trailers, debian/copyright, and
	# payload templates such as os-release and the APT source (NOTE-49).
	nimbus_render_tree "$dst"
	update_changelog "$dst" "$pkg"
}

# -----------------------------------------------------------------------------
# Building
# -----------------------------------------------------------------------------
build_package() {
	local pkg="$1" dst="$staging/$1" log_file="$staging/$1.build.log"
	local -a scripts debs

	if [[ -n "$opt_build_deps" ]]; then
		log "$pkg: installing Build-Depends"
		DEBIAN_FRONTEND=noninteractive apt-get build-dep -y -q --no-install-recommends "$dst/"
	fi

	# Maintainer scripts run under /bin/sh (dash): reject bash-only syntax.
	mapfile -t scripts < <(find "$dst/debian" -maxdepth 1 -type f \
		\( -name 'preinst' -o -name 'postinst' -o -name 'prerm' -o -name 'postrm' -o -name 'config' \
		-o -name '*.preinst' -o -name '*.postinst' -o -name '*.prerm' -o -name '*.postrm' -o -name '*.config' \) \
		| LC_ALL=C sort)
	if ((${#scripts[@]})); then
		checkbashisms -- "${scripts[@]}" || die "$pkg: maintainer scripts use bash-only syntax (see checkbashisms above)."
	fi

	log "$pkg: dpkg-buildpackage (log: $log_file)"
	if ! (cd "$dst" && dpkg-buildpackage -b -us -uc) 2>&1 | tee "$log_file" >&2; then
		die "$pkg: dpkg-buildpackage failed; full log in $log_file"
	fi

	mapfile -t debs < <(find "$staging" -maxdepth 1 -type f -name "${pkg}_${NIMBUS_VERSION}_*.deb")
	((${#debs[@]} == 1)) || die "$pkg: expected one ${pkg}_${NIMBUS_VERSION}_*.deb, found ${#debs[@]}."
	install -m 0644 -- "${debs[0]}" "$opt_out/"
}

main() {
	local pkg ver_env version deb
	local -a keys built deb_version_args=() selected=()

	while (($#)); do
		case "$1" in
			--out)                [[ $# -ge 2 ]] || die "--out needs a value"; opt_out="$2"; shift 2 ;;
			--tag)                [[ $# -ge 2 ]] || die "--tag needs a value"; opt_tag="$2"; shift 2 ;;
			--install-build-deps) opt_build_deps=1; shift ;;
			--lintian)            opt_lintian=1; shift ;;
			--allow-test-key)     opt_allow_test_key=1; shift ;;
			--only)               [[ $# -ge 2 ]] || die "--only needs a value"; opt_only="$2"; shift 2 ;;
			-h|--help)            usage; exit 0 ;;
			*) die "Unknown option: $1 (see --help)" ;;
		esac
	done

	nimbus_load_conf
	export LC_ALL=C.UTF-8
	opt_out="$(nimbus_path "${opt_out:-$NIMBUS_DEBS_DIR}")"
	staging="$(nimbus_path "$NIMBUS_STAGING_DIR")"

	# Which packages to build (all seven unless --only).
	if [[ -n "$opt_only" ]]; then
		IFS=',' read -r -a selected <<<"$opt_only"
		for pkg in "${selected[@]}"; do
			[[ " ${NIMBUS_PACKAGES[*]} " == *" $pkg "* ]] \
				|| die "--only: '$pkg' is not a NimbusOS package (${NIMBUS_PACKAGES[*]})."
		done
		warn "--only: building ${selected[*]} only. Such a partial set must never be published."
	else
		selected=("${NIMBUS_PACKAGES[@]}")
	fi

	# Host tools.
	if [[ -n "$opt_build_deps" ]]; then
		nimbus_require_root
		# gpg-agent is needed to generate the --allow-test-key key.
		nimbus_apt_install_missing dpkg-dev debhelper devscripts gpg gpg-agent gpgv git
		if [[ -n "$opt_lintian" ]]; then
			nimbus_apt_install_missing lintian
		fi
	fi
	for pkg in dpkg-buildpackage dpkg-parsechangelog checkbashisms gpg git; do
		command -v "$pkg" >/dev/null 2>&1 \
			|| die "$pkg is not installed. Install dpkg-dev, debhelper, devscripts, gpg and git, or use --install-build-deps."
	done
	if [[ -n "$opt_lintian" ]]; then
		command -v lintian >/dev/null 2>&1 || die "lintian is not installed (or use --install-build-deps)."
	fi

	# Version (one for all packages).
	if [[ -n "$opt_tag" ]]; then
		deb_version_args=(--tag "$opt_tag")
	fi
	ver_env="$("$NIMBUS_REPO_ROOT/tools/deb-version.sh" --env "${deb_version_args[@]}")"
	eval "$ver_env"
	export SOURCE_DATE_EPOCH
	# os-release(5) allows only 0-9, a-z, ".", "_" and "-" in VERSION_ID, so a
	# development version such as 0.2.0+git20261117.5.gabc1234 is written as
	# 0.2.0.git20261117.5.gabc1234 there.
	# shellcheck disable=SC2034  # read by name when the @NIMBUS_*@ tokens are filled in (os-release, Plasma theme)
	NIMBUS_OS_VERSION_ID="$(printf '%s' "${NIMBUS_DISPLAY_VERSION,,}" | tr -c '0-9a-z._-' '.')"
	step "Building ${NIMBUS_NAME} packages $NIMBUS_VERSION (channel $NIMBUS_CHANNEL, commit $NIMBUS_GIT_COMMIT)"

	# Maintainer identity (docs/PLAN.md A11).
	# (The pattern lives in a variable: written inline, glibc would read \< and
	# \> as word boundaries rather than literal angle brackets.)
	local maintainer_re='^[^<>]+ <[^<>[:space:]@]+@[^<>[:space:]]+>$'
	[[ "$NIMBUS_MAINTAINER" =~ $maintainer_re ]] \
		|| die "NIMBUS_MAINTAINER must look like 'Full Name <address>', got: $NIMBUS_MAINTAINER"

	# Keys.
	nimbus_check_docker_key
	mapfile -t keys < <(nimbus_archive_key_files)
	if ((${#keys[@]} == 0)); then
		[[ -n "$opt_allow_test_key" ]] || die "No NimbusOS public key is committed in $NIMBUS_ARCHIVE_KEYS_DIR/. Create one as described in docs/SIGNING.md. (CI test builds only: --allow-test-key.)"
		make_test_key
	fi

	# Clean outputs of earlier runs, then stage and build every package.
	mkdir -p -- "$opt_out" "$staging"
	for pkg in "${selected[@]}"; do
		rm -f -- "$opt_out/${pkg}_"*.deb "$staging/${pkg}_"*.deb "$staging/${pkg}_"*.buildinfo "$staging/${pkg}_"*.changes
	done
	for pkg in "${selected[@]}"; do
		step "$pkg"
		stage_package "$pkg"
		build_package "$pkg"
	done

	# The result must be one consistent set (each package checked on its own
	# with --only).
	if [[ -z "$opt_only" ]]; then
		version="$(nimbus_check_deb_set "$opt_out")"
		[[ "$version" == "$NIMBUS_VERSION" ]] || die "Built packages have version $version, expected $NIMBUS_VERSION."
	fi
	deb="$(find "$opt_out" -maxdepth 1 -name "nimbusos-archive-keyring_${NIMBUS_VERSION}_*.deb" -print -quit)"
	if [[ -n "$deb" && -z "$NIMBUS_TEST_KEY" ]]; then
		nimbus_check_archive_keyring_deb "$deb"
	fi
	deb="$(find "$opt_out" -maxdepth 1 -name "nimbusos-docker-keyring_${NIMBUS_VERSION}_*.deb" -print -quit)"
	if [[ -n "$deb" ]]; then
		nimbus_check_docker_keyring_deb "$deb"
	fi

	if [[ -n "$opt_lintian" ]]; then
		step "lintian"
		mapfile -t built < <(for pkg in "${selected[@]}"; do
			find "$opt_out" -maxdepth 1 -name "${pkg}_${NIMBUS_VERSION}_*.deb"
		done)
		# .debs, not .changes: suite names such as "beta" are not Debian
		# suites, and that is expected for this repository.
		lintian --fail-on error,warning --info -- "${built[@]}"
	fi

	# Version values for the next step (build.sh, CI).
	printf '%s\n' "$ver_env" "NIMBUS_TEST_KEY=${NIMBUS_TEST_KEY}" >"$opt_out/nimbus-version.env"

	step "Done: $NIMBUS_VERSION"
	for pkg in "${selected[@]}"; do
		find "$opt_out" -maxdepth 1 -name "${pkg}_${NIMBUS_VERSION}_*.deb" -printf '  %f\n' >&2
	done
	if [[ -n "$NIMBUS_TEST_KEY" ]]; then
		warn "Built with a THROWAWAY archive key (--allow-test-key). Do not publish these packages."
	fi
}

main "$@"
