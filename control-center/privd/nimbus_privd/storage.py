# =============================================================================
# nimbus_privd/storage.py: disks, the pool and parity
# =============================================================================
# What: disk.list       every disk from lsblk --json with its partitions,
#                       role (system, data, parity, unassigned), whether it
#                       carries the running system or the live medium, and
#                       SMART from a cache refreshed hourly with
#                       "smartctl -n standby" (a sleeping disk is not woken);
#                       plus the managed fstab entries and the pool's state
#       disk.smart      refresh one disk's SMART now
#       disk.format     wipe, GPT with one partition, mkfs.xfs (default),
#                       mkfs.ext4 or mkfs.btrfs with the label, a UUID= fstab
#                       entry with nofail, mounted at /mnt/disks/<label> (data)
#                       or /mnt/parity/<label> (parity). Refused for the
#                       system disk, the live medium, a disk with anything
#                       mounted, a wrong serial, a used label, and in the
#                       live session
#       disk.mount      add an existing filesystem (after a reinstall)
#       disk.unmount    unmount and drop the fstab entry; data stays; refused
#                       while the disk is in the pool or parity set
#       pool.apply      single, pooled (mergerfs at /mnt/user, create policy
#                       mfs or epmfs; branches change on a mounted pool
#                       through its .mergerfs control file) or pooled +
#                       parity (/etc/nimbus/snapraid.conf, parity at least as
#                       large as every data disk)
#       snapraid.status the last sync and scrub (nimbus-snapraid-run) and
#                       what "snapraid diff" lists: counts, and the size of
#                       the files not yet protected (cached 10 minutes)
#       snapraid.sync_now  starts nimbus-snapraid-sync.service
# Why:  spec Tab C (Disks, Pool); docs/PLAN.md §4.5, NOTE-26, NOTE-68.
# =============================================================================

