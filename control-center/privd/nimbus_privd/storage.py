SYSTEM_MOUNTS = ("/", "/boot", "/boot/efi", "/usr", "/var", "/home", "/srv", "/opt", "[SWAP]")
LIVE_MEDIUM = "/run/live/medium"


def device(value, field="device"):
    if not isinstance(value, str) or not re.fullmatch(r"/dev/[a-z][a-z0-9]{1,31}", value):
        raise ValidationError(field, "Not a disk device (for example /dev/sdb).")
    return value


def text(limit):
    def check(value, field):
        if not isinstance(value, str) or len(value) > limit or any(c in value for c in "\x00\n"):
            raise ValidationError(field, f"Must be text of at most {limit} characters.")
        return value.strip()
    return check


def labels(max_items):
    def check(value, field):
        if not isinstance(value, list) or len(value) > max_items:
            raise ValidationError(field, f"A list of at most {max_items} disk labels.")
        out = [disk_label(v, field) for v in value]
        if len(set(out)) != len(out):
            raise ValidationError(field, "A disk is listed twice.")
        return out
    return check


def live_session():
    try:
        with open("/proc/cmdline", encoding="ascii") as f:
            if "boot=live" in f.read().split():
                return True
    except OSError:
        pass
    return os.path.isdir(LIVE_MEDIUM) and os.path.ismount(LIVE_MEDIUM)


def refuse_in_live():
    if live_session():
        raise ValidationError("live", "Install NimbusOS to set up storage. Disks can't be changed in the live session.")


# --- reading -------------------------------------------------------------------------------------
def _walk(dev):
    yield dev
    for child in dev.get("children") or []:
        yield from _walk(child)


def _mounts(dev):
    return [m for d in _walk(dev) for m in (d.get("mountpoints") or []) if m]


def describe(dev, smart=None):
    mounts = _mounts(dev)
    system = any(m in SYSTEM_MOUNTS or m.startswith("/boot/") for m in mounts)
    live = any(m == LIVE_MEDIUM or m.startswith("/run/live/") for m in mounts)
    role, label = "unassigned", None
    for m in mounts:
        if m.startswith(S.DISKS + "/"):
            role, label = "data", m.rsplit("/", 1)[1]
        elif m.startswith(S.PARITY + "/"):
            role, label = "parity", m.rsplit("/", 1)[1]
    if system or live:
        role = "system"
    parts = [{"path": p["path"], "size": p.get("size"), "fstype": p.get("fstype"), "label": p.get("label"),
              "uuid": p.get("uuid"), "mountpoints": [m for m in (p.get("mountpoints") or []) if m]}
             for p in dev.get("children") or [] if p.get("type") == "part"]
    fs = (parts[0]["fstype"] if parts else dev.get("fstype")) or None
    return {"name": dev["name"], "path": dev["path"], "size": dev.get("size"), "model": (dev.get("model") or "").strip(),
            "serial": (dev.get("serial") or "").strip(), "rotational": bool(dev.get("rota")),
            "transport": dev.get("tran"), "removable": bool(dev.get("rm") or dev.get("hotplug")),
            "system": system, "live": live, "mounted": bool(mounts), "mounts": mounts, "role": role, "label": label,
            "fstype": fs, "partitions": parts, "smart": smart}


def scan():
    tree = json.loads(runner.run([LSBLK, "--json", "--bytes", "--output", COLUMNS], timeout=30).stdout)
    return [d for d in tree.get("blockdevices", [])
            if d.get("type") == "disk" and not d["name"].startswith(("loop", "zram", "ram"))]


def smart_summary(doc):
    """The parts of smartctl --json the UI and the alerts use."""
    messages = " ".join(m.get("string", "") for m in (doc.get("smartctl") or {}).get("messages", []))
    exit_status = (doc.get("smartctl") or {}).get("exit_status", 0)
    asleep = "STANDBY" in messages.upper() or "SLEEP" in messages.upper()
    attrs = {a.get("id"): (a.get("raw") or {}).get("value") for a in (doc.get("ata_smart_attributes") or {}).get("table", [])}
    nvme = doc.get("nvme_smart_health_information_log") or {}
    passed = (doc.get("smart_status") or {}).get("passed")
    return {
        "passed": passed, "asleep": asleep, "temperature": (doc.get("temperature") or {}).get("current"),
        "reallocated": attrs.get(5), "pending": attrs.get(197), "media_errors": nvme.get("media_errors"),
        "power_on_hours": (doc.get("power_on_time") or {}).get("hours"),
        "nvme": doc.get("device", {}).get("type") == "nvme" or bool(nvme),
        "error": None if passed is not None or asleep else (messages.strip() or f"smartctl exit status {exit_status}"),
        "checked": int(time.time()),
    }


def _cache_name(dev):
    key = dev.get("serial") or dev["name"]
    return re.sub(r"[^A-Za-z0-9_.-]", "_", str(key).strip())[:100] + ".json"


def smart(dev, refresh=False):
    path = os.path.join(SMART_CACHE, _cache_name(dev))
    try:
        with open(path, encoding="utf-8") as f:
            cached = json.load(f)
    except (OSError, ValueError):
        cached = None
    if cached and not refresh and time.time() - cached.get("checked", 0) < SMART_MAX_AGE:
        return cached
    proc = runner.run([SMARTCTL, "--json", "--all", "--nocheck=standby", dev["path"]], timeout=60, check=False)
    try:
        summary = smart_summary(json.loads(proc.stdout))
    except ValueError:
        summary = {"passed": None, "asleep": False, "error": "smartctl gave no readable answer.", "checked": int(time.time())}
    if summary["asleep"] and cached:                      # keep the last real reading, say it sleeps
        summary = {**cached, "asleep": True, "checked": int(time.time())}
    os.makedirs(SMART_CACHE, mode=0o700, exist_ok=True)
    fsutil.write_atomic(path, json.dumps(summary), 0o600)
    return summary


def pool_state():
    mounted = os.path.ismount(S.POOL)
    usage = None
    if mounted:
        st = os.statvfs(S.POOL)
        usage = {"total": st.f_blocks * st.f_frsize, "free": st.f_bavail * st.f_frsize}
    return {"mounted": mounted, "usage": usage, "snapraid": os.path.exists(SNAPRAID), "parity_configured": os.path.exists(SNAPRAID_CONF)}


@REGISTRY.verb("disk.list")
def disk_list(ctx, args):
    disks = [describe(d, smart(describe(d))) for d in scan()]
    entries = fsutil.read_block()
    for e in entries:
        if e["kind"] == "disk":
            root = S.DISKS if e["role"] == "data" else S.PARITY
            e["mounted"] = os.path.ismount(f"{root}/{e['label']}")
            e["present"] = any(p.get("uuid") == e["uuid"] for d in disks for p in d["partitions"])
    return {"disks": disks, "fstab": entries, "pool": pool_state(), "live": live_session()}


@REGISTRY.verb("disk.smart", args={"device": Arg(device)})
def disk_smart(ctx, args):
    dev = next((d for d in scan() if d["path"] == args["device"]), None)
    if dev is None:
        raise ValidationError("device", f"{args['device']} is not a disk on this computer.")
    return smart(describe(dev), refresh=True)


# --- changing disks ------------------------------------------------------------------------------
def _mountpoint(role, label):
    return f"{S.DISKS if role == 'data' else S.PARITY}/{label}"


def _check_label_free(label, entries):
    if any(e["kind"] == "disk" and e["label"] == label for e in entries):
        raise ValidationError("label", f"The label '{label}' is already used by another disk. Choose another.")
    for root in (S.DISKS, S.PARITY):
        if os.path.ismount(f"{root}/{label}"):
            raise ValidationError("label", f"Something is already mounted at {root}/{label}.")


def _mount(ctx, role, label):
    target = _mountpoint(role, label)
    os.makedirs(target, mode=0o755, exist_ok=True)
    runner.run([MOUNT, target], timeout=120)
    ctx.log(f"Mounted at {target}")
    return target


@REGISTRY.verb("disk.format", stream=True, lock="storage", args={
    "device": Arg(device), "serial": Arg(text(128)), "fs": Arg(lambda v, f: one_of(v, FILESYSTEMS, f)),
    "label": Arg(disk_label), "role": Arg(lambda v, f: one_of(v, ("data", "parity"), f))})
def disk_format(ctx, args):
    refuse_in_live()
    raw = next((d for d in scan() if d["path"] == args["device"]), None)
    if raw is None:
        raise ValidationError("device", f"{args['device']} is not a disk on this computer.")
    dev = describe(raw)
    if dev["system"] or dev["live"]:
        raise ValidationError("device", f"{dev['path']} holds the running system or the live medium; it can't be formatted.")
    if dev["mounted"]:
        raise ValidationError("device", f"{dev['path']} has mounted filesystems ({', '.join(dev['mounts'])}). "
                                        "Unmount them first.")
    expected = dev["serial"] or dev["name"]
    if args["serial"] != expected:
        raise ValidationError("serial", f"That is not the {'serial number' if dev['serial'] else 'name'} of this disk.")
    entries = fsutil.read_block()
    _check_label_free(args["label"], entries)

    ctx.log(f"Erasing {dev['path']} ({dev['model'] or 'disk'}, {dev['size']} bytes)")
    for part in reversed(dev["partitions"]):
        runner.run([WIPEFS, "--all", "--force", part["path"]], timeout=120)
    runner.run([WIPEFS, "--all", "--force", dev["path"]], timeout=120)
    runner.run([PARTED, "--script", dev["path"], "mklabel", "gpt", "mkpart", args["label"], args["fs"], "1MiB", "100%"],
               timeout=120)
    runner.run([UDEVADM, "settle", "--timeout=30"], timeout=60, check=False)
    part = None
    for _ in range(50):
        new = next((d for d in scan() if d["path"] == dev["path"]), {})
        part = next((p["path"] for p in new.get("children") or [] if p.get("type") == "part"), None)
        if part and os.path.exists(part):
            break
        time.sleep(0.2)
    if not part or not os.path.exists(part):
        raise ValidationError("device", f"The new partition on {dev['path']} did not appear.")
    ctx.log(f"Creating {args['fs']} on {part} with the label {args['label']}")
    extra = (["-m", "0" if args["role"] == "parity" else "1"] if args["fs"] == "ext4" else [])
    runner.run([*MKFS[args["fs"]], args["label"], *extra, part], timeout=1800)
    uuid = runner.run([BLKID, "-o", "value", "-s", "UUID", part], timeout=30).stdout.strip()
    if not re.fullmatch(r"[A-Za-z0-9-]{8,64}", uuid):
        raise ValidationError("device", f"blkid found no UUID on {part}.")
    fsutil.write_block([*entries, {"kind": "disk", "role": args["role"], "label": args["label"], "uuid": uuid,
                                   "fs": args["fs"]}], ctx.log)
    target = _mount(ctx, args["role"], args["label"])
    return {"label": args["label"], "uuid": uuid, "mountpoint": target, "fs": args["fs"], "role": args["role"]}


@REGISTRY.verb("disk.mount", stream=True, lock="storage", args={
    "partition": Arg(device), "label": Arg(disk_label), "role": Arg(lambda v, f: one_of(v, ("data", "parity"), f))})
def disk_mount(ctx, args):
    refuse_in_live()
    found = None
    for raw in scan():
        dev = describe(raw)
        for p in dev["partitions"]:
            if p["path"] == args["partition"]:
                found = (dev, p)
    if found is None:
        raise ValidationError("partition", f"{args['partition']} is not a partition on this computer.")
    dev, part = found
    if dev["system"] or dev["live"] or part["mountpoints"]:
        raise ValidationError("partition", f"{part['path']} is in use already.")
    if part["fstype"] not in FILESYSTEMS or not part["uuid"]:
        raise ValidationError("partition", f"{part['path']} has no XFS, ext4 or btrfs filesystem to add.")
    entries = fsutil.read_block()
    _check_label_free(args["label"], entries)
    fsutil.write_block([*entries, {"kind": "disk", "role": args["role"], "label": args["label"], "uuid": part["uuid"],
                                   "fs": part["fstype"]}], ctx.log)
    return {"label": args["label"], "mountpoint": _mount(ctx, args["role"], args["label"])}


@REGISTRY.verb("disk.unmount", stream=True, lock="storage", args={"label": Arg(disk_label)})
def disk_unmount(ctx, args):
    entries = fsutil.read_block()
    entry = next((e for e in entries if e["kind"] == "disk" and e["label"] == args["label"]), None)
    if entry is None:
        raise ValidationError("label", f"No disk is set up with the label '{args['label']}'.")
    pool = next((e for e in entries if e["kind"] == "pool"), None)
    if pool and args["label"] in pool["branches"]:
        raise ValidationError("label", f"'{args['label']}' is part of the pool. Remove it from the pool first.")
    if _in_parity_conf(args["label"]):
        raise ValidationError("label", f"'{args['label']}' is part of the parity set. Change the pool first.")
    target = _mountpoint(entry["role"], entry["label"])
    if os.path.ismount(target):
        proc = runner.run([UMOUNT, target], timeout=120, check=False)
        if proc.returncode != 0:
            raise ValidationError("label", f"{target} is in use (apps, VMs or open files?). Close them and try again.")
    fsutil.write_block([e for e in entries if e is not entry], ctx.log)
    try:
        os.rmdir(target)
    except OSError:
        pass
    ctx.log(f"Unmounted {target}; the data on the disk is untouched.")
    return {"label": args["label"]}


# --- the pool and parity -----------------------------------------------------------------------------
def _in_parity_conf(label):
    try:
        with open(SNAPRAID_CONF, encoding="utf-8") as f:
            return any(f"/{label}/" in line for line in f if not line.startswith("#"))
    except FileNotFoundError:
        return False


def _fs_size(path):
    st = os.statvfs(path)
    return st.f_blocks * st.f_frsize


def render_snapraid(data, parity):
    names = ["parity", "2-parity"]
    lines = [f"{MARKER}. Do not edit: change the pool in the Control Center.",
             "# Parity is updated by nimbus-snapraid-sync.timer (nightly), not in real time."]
    lines += [f"{names[i]} {S.PARITY}/{label}/snapraid.{names[i]}" for i, label in enumerate(parity)]
    lines += [f"content {SNAPRAID_CONTENT}"] + [f"content {S.DISKS}/{label}/.snapraid.content" for label in data]
    lines += [f"data {label} {S.DISKS}/{label}/" for label in data]
    lines += ["exclude *.unrecoverable", "exclude /lost+found/", "exclude .recycle/", "exclude .Trash-*/",
              "exclude *.nimbus-tmp", "autosave 500"]
    return "\n".join(lines) + "\n"


@REGISTRY.verb("pool.apply", stream=True, lock="storage", args={
    "mode": Arg(lambda v, f: one_of(v, ("single", "pooled", "parity"), f)),
    "policy": Arg(lambda v, f: one_of(v, ("mfs", "epmfs"), f), required=False, default="mfs"),
    "data": Arg(labels(24), required=False, default=[]), "parity": Arg(labels(2), required=False, default=[])})
def pool_apply(ctx, args):
    refuse_in_live()
    mode, data, parity = args["mode"], args["data"], args["parity"]
    entries = fsutil.read_block()
    disks = {e["label"]: e for e in entries if e["kind"] == "disk"}
    for label in data + parity:
        if label not in disks:
            raise ValidationError("data", f"No disk is set up with the label '{label}'.")
    for label in data:
        if disks[label]["role"] != "data" or not os.path.ismount(_mountpoint("data", label)):
            raise ValidationError("data", f"'{label}' is not a mounted data disk.")
    for label in parity:
        if disks[label]["role"] != "parity" or not os.path.ismount(_mountpoint("parity", label)):
            raise ValidationError("parity", f"'{label}' is not a mounted parity disk.")
    if mode in ("pooled", "parity") and not data:
        raise ValidationError("data", "A pool needs at least one data disk.")
    if mode == "parity":
        if not os.path.exists(SNAPRAID):
            raise ValidationError("mode", "SnapRAID isn't installed (sudo apt install snapraid), so parity isn't available.")
        if not parity:
            raise ValidationError("parity", "Pooled + parity needs one or two parity disks.")
        largest = max(_fs_size(_mountpoint("data", d)) for d in data)
        for label in parity:
            if _fs_size(_mountpoint("parity", label)) < largest:
                raise ValidationError("parity", f"The parity disk '{label}' is smaller than the largest data disk. "
                                                "Parity must be at least as large.")
    elif parity:
        raise ValidationError("parity", "Parity disks are only used in Pooled + parity mode.")

    others = [e for e in entries if e["kind"] != "pool"]
    if mode == "single":
        if os.path.ismount(S.POOL):
            if runner.run([UMOUNT, S.POOL], timeout=120, check=False).returncode != 0:
                raise ValidationError("mode", f"{S.POOL} is in use (shares, apps or VMs?). Stop them first.")
        fsutil.write_block(others, ctx.log)
    else:
        pool = {"kind": "pool", "branches": data, "policy": args["policy"]}
        fsutil.write_block([*others, pool], ctx.log)
        control = os.path.join(S.POOL, ".mergerfs")
        if os.path.ismount(S.POOL) and os.path.exists(control):
            os.setxattr(control, "user.mergerfs.branches", ":".join(f"{S.DISKS}/{d}" for d in data).encode())
            os.setxattr(control, "user.mergerfs.category.create", args["policy"].encode())
            ctx.log(f"Changed the pool's disks to {', '.join(data)} (create policy {args['policy']})")
        else:
            os.makedirs(S.POOL, mode=0o755, exist_ok=True)
            runner.run([MOUNT, S.POOL], timeout=120)
            ctx.log(f"Mounted the pool at {S.POOL} over {', '.join(data)}")
    if mode == "parity":
        os.makedirs(os.path.dirname(SNAPRAID_CONF), mode=0o755, exist_ok=True)
        os.makedirs(os.path.dirname(SNAPRAID_CONTENT), mode=0o700, exist_ok=True)
        fsutil.write_atomic(SNAPRAID_CONF, render_snapraid(data, parity), 0o644)
        ctx.log(f"Wrote {SNAPRAID_CONF}: parity on {', '.join(parity)}, synced nightly")
    elif os.path.exists(SNAPRAID_CONF):
        stamp = time.strftime("%Y%m%dT%H%M%S")
        keep = os.path.dirname(SNAPRAID_CONTENT)
        os.makedirs(keep, mode=0o700, exist_ok=True)
        os.replace(SNAPRAID_CONF, os.path.join(keep, f"snapraid.conf.{stamp}"))
        ctx.log(f"Parity is off; the old SnapRAID configuration was kept in {keep}")
    return {"mode": mode, "data": data, "parity": parity, "policy": args["policy"], **pool_state()}


DIFF_KEYS = ("equal", "added", "removed", "updated", "moved", "copied", "restored")


def parse_diff(output):
    counts = {}
    for line in output.splitlines():
        m = re.fullmatch(r"\s*(\d+)\s+(equal|added|removed|updated|moved|copied|restored)\s*", line)
        if m:
            counts[m.group(2)] = int(m.group(1))
    return counts


CHANGED = re.compile(r"(add|update|restore|move|copy|relocate) (.+)")       # snapraid's cmdline/scan.c


def term_paths(text):
    """The paths in snapraid's terminal form of a diff line's file: shell
    escaping ("my\\ film\\ \\(1\\).mkv"; a backslash keeps the next
    character), and an unescaped " -> " between a move's, copy's or
    relocation's old and new path (spaces in names are always escaped, so
    it can't be part of one)."""
    paths, current, i = [], [], 0
    while i < len(text):
        if text[i] == "\\" and i + 1 < len(text):
            current.append(text[i + 1])
            i += 2
        elif text.startswith(" -> ", i):
            paths.append("".join(current))
            current, i = [], i + 4
        else:
            current.append(text[i])
            i += 1
    return paths + ["".join(current)]


def unprotected_bytes(output, data_labels):
    """The size of the files "snapraid diff" lists as added, updated,
    restored, moved, copied or relocated: what a failed disk would lose today.
    snapraid names a file by its path inside its disk, not by the disk
    ("add media/new.mkv", read from a real diff in nas-integration.sh), so
    it is looked up on the data disks; a path listed again (changed on two
    disks) counts on the next disk that holds it."""
    listed = collections.Counter()
    total = 0
    for line in output.splitlines():
        m = CHANGED.fullmatch(line)
        if not m:
            continue
        path = term_paths(m.group(2))[-1]
        if not path or path.startswith("/") or ".." in path.split("/"):
            continue
        sizes = []
        for label in sorted(data_labels):
            try:
                st = os.lstat(f"{S.DISKS}/{label}/{path}")
            except OSError:
                continue
            if not stat.S_ISDIR(st.st_mode):                 # a link counts as itself, never its target
                sizes.append(st.st_size)
        if listed[path] < len(sizes):
            total += sizes[listed[path]]
        listed[path] += 1
    return total


@REGISTRY.verb("snapraid.status", lock="snapraid-status")
def snapraid_status(ctx, args):
    out = {"configured": os.path.exists(SNAPRAID_CONF), "installed": os.path.exists(SNAPRAID)}
    try:
        with open(SNAPRAID_STATUS, encoding="utf-8") as f:
            out["last"] = json.load(f)
    except (OSError, ValueError):
        out["last"] = None
    active = runner.run([SYSTEMCTL, "is-active", SNAPRAID_UNIT], timeout=15, check=False).stdout.strip() \
        if os.path.isdir("/run/systemd/system") else "unknown"
    out["running"] = active in ("active", "activating")
    if out["configured"] and out["installed"] and not out["running"]:
        try:
            with open(SNAPRAID_DIFF, encoding="utf-8") as f:
                cached = json.load(f)
        except (OSError, ValueError):
            cached = None
        if not cached or time.time() - cached.get("checked", 0) > 600:
            proc = runner.run([SNAPRAID, "-c", SNAPRAID_CONF, "diff"], timeout=600, check=False)
            labels = {e["label"] for e in fsutil.read_block() if e["kind"] == "disk" and e["role"] == "data"}
            cached = {"counts": parse_diff(proc.stdout), "bytes": unprotected_bytes(proc.stdout, labels),
                      "exit": proc.returncode, "checked": int(time.time())}
            fsutil.write_atomic(SNAPRAID_DIFF, json.dumps(cached), 0o600)
        changed = sum(cached["counts"].get(k, 0) for k in DIFF_KEYS if k != "equal")
        out["diff"] = {**cached, "unprotected": changed, "bytes": cached.get("bytes", 0)}
    return out


@REGISTRY.verb("snapraid.sync_now", lock="snapraid-status")
def snapraid_sync_now(ctx, args):
    if not os.path.exists(SNAPRAID_CONF):
        raise ValidationError("mode", "Parity is not set up.")
    runner.run([SYSTEMCTL, "start", "--no-block", SNAPRAID_UNIT], timeout=30)
    return {"started": True}
