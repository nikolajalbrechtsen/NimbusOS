# =============================================================================
# nimbus_privd/samba.py: shares, SMB users and Samba's settings
# =============================================================================
# What: share.apply {shares, settings}
#         renders /etc/samba/nimbus-shares.conf and settings.conf from the
#         structured share list (privd computes every path itself from the
#         share's name and location), checks the candidate set with
#         "testparm -s" (testparm exits 0 on unknown parameters, so its
#         messages are read too), swaps the files in atomically, reloads
#         smbd, checks the live configuration again and restores the old
#         files on any failure. It also makes missing share folders
#         (root:nimbus-smb, setgid 2775), writes the Avahi service
#         (_smb, plus _adisk for Time Machine) and bind-mounts the "isos"
#         share onto the VM ISO library (NOTE-27). A share whose disk isn't
#         mounted is published as unavailable, and nothing is created on
#         the system disk in its place.
#       share.delete_data {name, location}: deletes a share's folder,
#         link-safe, only when no exported share uses it.
#       samba.settings {enabled, netbios}: smbd and wsdd2 on or off, nmbd
#         with NetBIOS.
#       samba.test {user, password}: "smbclient -L localhost" with the
#         password in a 0600 file, never on a command line.
#       smbuser.add / .passwd / .delete / .list: SMB-only users are system
#         accounts in nimbus-smb (adduser --system); an existing desktop
#         account (uid 1000 and up) is added to nimbus-smb instead.
#         Passwords go to "smbpasswd -s" on stdin and are never logged.
# Why:  spec Tab C (Shares, SMB users, Samba config generation); docs/PLAN.md
#       §4.5, NOTE-23, NOTE-24, NOTE-25, NOTE-27, NOTE-68.
# =============================================================================

