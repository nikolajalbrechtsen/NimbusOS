# --- folders -----------------------------------------------------------------------------------
def _bool(value, field):
    if not isinstance(value, bool):
        raise ValidationError(field, "Must be true or false.")
    return value


def _ensure_dir(root, name, log):
    """Make ROOT/NAME (root:nimbus-smb, 2775) without following links."""
    gid = grp.getgrnam(GROUP).gr_gid
    if root == S.SYSTEM_SHARES:
        os.makedirs(S.SYSTEM_SHARES, mode=0o755, exist_ok=True)
    rfd = fsutil.open_dir(root)
    try:
        try:
            os.mkdir(name, 0o2775, dir_fd=rfd)
            log(f"Created {root}/{name}")
        except FileExistsError:
            pass
        try:
            fd = os.open(name, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=rfd)
        except OSError:
            raise ValidationError("shares", f"{root}/{name} is not a plain folder (a link or a file is in the way).") from None
        try:
            os.fchown(fd, 0, gid)
            os.fchmod(fd, 0o2775)
        finally:
            os.close(fd)
    finally:
        os.close(rfd)


# --- rendering -----------------------------------------------------------------------------------
def render_settings(settings, shares):
    guests = any(s["smb"] and s["security"] in ("public", "secure") for s in shares)
    return "\n".join([
        f"# {MARKER} from /var/lib/nimbus-control/settings.json. Do not edit: use the Control Center (Settings).",
        "[global]",
        f"   workgroup = {settings['workgroup']}",
        f"   server string = {settings['description'] or 'NimbusOS'}",
        f"   disable netbios = {'no' if settings['netbios'] else 'yes'}",
        f"   map to guest = {'Bad User' if guests else 'Never'}",
    ]) + "\n"


def render_share(share, available):
    s = share
    vfs = ["catia", "fruit", "streams_xattr"] + (["recycle"] if s["recycle"]["enabled"] else [])
    lines = [f"[{s['name']}]", f"   path = {share_path(s)}", f"   browseable = {'yes' if s['browseable'] else 'no'}",
             f"   force group = {GROUP}", "   create mask = 0664", "   force create mode = 0664",
             "   directory mask = 2775", "   force directory mode = 2775", f"   vfs objects = {' '.join(vfs)}"]
    rw = sorted(u for u, a in s["users"].items() if a == "rw")
    ro = sorted(u for u, a in s["users"].items() if a == "ro")
    if s["security"] == "public":
        lines += ["   guest ok = yes", "   read only = no"]
    elif s["security"] == "secure":
        lines += ["   guest ok = yes", "   read only = yes"] + ([f"   write list = {' '.join(rw)}"] if rw else [])
    else:
        lines += ["   guest ok = no", "   read only = yes"]
        if rw or ro:
            lines.append(f"   valid users = {' '.join(sorted(rw + ro))}")
            if rw:
                lines.append(f"   write list = {' '.join(rw)}")
        else:
            available = False                    # private and nobody has access
    if s["recycle"]["enabled"]:
        lines += ["   recycle:repository = .recycle", "   recycle:keeptree = yes", "   recycle:versions = yes",
                  "   recycle:touch = yes", "   recycle:touch_mtime = yes", "   recycle:directory_mode = 2775",
                  "   recycle:exclude = *.tmp,*.temp,~$*", "   recycle:exclude_dir = .recycle"]
    if s["timemachine"]["enabled"]:
        lines.append("   fruit:time machine = yes")
        if s["timemachine"]["max_gb"]:
            lines.append(f"   fruit:time machine max size = {s['timemachine']['max_gb']}G")
    if s["hosts_allow"]:
        lines.append(f"   hosts allow = {s['hosts_allow']} 127.0.0.1")
    if not available:
        lines.append("   available = no")
    return "\n".join(lines)


def render_shares(shares, availability):
    body = [render_share(s, availability[s["name"]]) for s in shares if s["smb"]]
    head = f"# {MARKER} from /var/lib/nimbus-control/shares.json. Do not edit: use the Control Center (Shares)."
    return "\n\n".join([head, *body]) + "\n"


def render_avahi(shares):
    tm = [s for s in shares if s["smb"] and s["timemachine"]["enabled"]]
    lines = ['<?xml version="1.0" standalone="no"?>', '<!DOCTYPE service-group SYSTEM "avahi-service.dtd">',
             f"<!-- {MARKER}: SMB for macOS Finder and Linux file managers (docs/PLAN.md NOTE-24). -->",
             "<service-group>", '  <name replace-wildcards="yes">%h</name>',
             "  <service><type>_smb._tcp</type><port>445</port></service>",
             "  <service><type>_device-info._tcp</type><port>0</port><txt-record>model=RackMac</txt-record></service>"]
    if tm:
        lines.append("  <service><type>_adisk._tcp</type><port>9</port>")
        lines.append("    <txt-record>sys=waMa=0,adVF=0x100</txt-record>")
        for i, s in enumerate(tm):
            lines.append(f"    <txt-record>dk{i}=adVN={s['name']},adVF=0x82</txt-record>")
        lines.append("  </service>")
    lines.append("</service-group>")
    return "\n".join(lines) + "\n"


# --- applying ------------------------------------------------------------------------------------
def _read(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except FileNotFoundError:
        return None


def _testparm(conf, label):
    proc = runner.run([TESTPARM, "-s", conf], timeout=60, check=False)
    problems = [line for line in proc.stderr.splitlines() if any(f in line for f in TESTPARM_FAILURES)]
    if proc.returncode != 0 or problems:
        detail = "; ".join(problems[:3]) or proc.stderr.strip().splitlines()[-1:] or ["testparm failed"]
        raise runner.CommandFailed([TESTPARM, "-s", label], proc.returncode or 1,
                                   detail if isinstance(detail, str) else " ".join(detail))


def ensure_include(log):
    """NOTE-23's fallback: put the include block back if smb.conf lost it."""
    text = _read(SMB_CONF) or ""
    if any(line.strip() == INCLUDE_LINE for line in text.splitlines()):
        return False
    block = f"\n# BEGIN nimbus-control (docs/PLAN.md NOTE-23)\n{INCLUDE_LINE}\n# END nimbus-control\n"
    fsutil.write_atomic(SMB_CONF, text.rstrip("\n") + "\n" + block, 0o644)
    log(f"The NimbusOS include was missing from {SMB_CONF}; it was put back.")
    return True


def _candidate(tmp, settings_text, shares_text):
    """A copy of the whole configuration that points at the new files."""
    paths = {"settings": os.path.join(tmp, "settings.conf"), "shares": os.path.join(tmp, "shares.conf"),
             "nimbus": os.path.join(tmp, "nimbus.conf"), "smb": os.path.join(tmp, "smb.conf")}
    with open(paths["settings"], "w", encoding="utf-8") as f:
        f.write(settings_text)
    with open(paths["shares"], "w", encoding="utf-8") as f:
        f.write(shares_text)
    nimbus = (_read(NIMBUS_CONF) or "").replace(f"include = {SETTINGS_CONF}", f"include = {paths['settings']}") \
        .replace(f"include = {SHARES_CONF}", f"include = {paths['shares']}")
    with open(paths["nimbus"], "w", encoding="utf-8") as f:
        f.write(nimbus)
    smb = (_read(SMB_CONF) or "").replace(INCLUDE_LINE, f"include = {paths['nimbus']}")
    with open(paths["smb"], "w", encoding="utf-8") as f:
        f.write(smb)
    return paths["smb"]


def smbd_running():
    if os.path.isdir("/run/systemd/system"):
        return runner.run([SYSTEMCTL, "is-active", "--quiet", "smbd.service"], timeout=15, check=False).returncode == 0
    for pid in os.listdir("/proc"):                     # without systemd (containers, tests)
        try:
            with open(f"/proc/{pid}/comm", encoding="ascii", errors="replace") as f:
                if pid.isdigit() and f.read().strip() == "smbd":
                    return True
        except OSError:
            continue
    return False


def _reload():
    if smbd_running():
        runner.run([SMBCONTROL, "smbd", "reload-config"], timeout=30)


def _isos_bind(shares, log):
    entries = fsutil.read_block()
    current = next((e for e in entries if e["kind"] == "isos"), None)
    share = next((s for s in shares if s["name"] == "isos"), None)
    wanted = None
    if share and location_root(share["location"])[1]:
        wanted = share_path(share)
    if (current or {}).get("source") == wanted:
        if wanted and not os.path.ismount(S.ISOS):
            runner.run([MOUNT, S.ISOS], timeout=60)
        return
    if current and os.path.ismount(S.ISOS):
        if runner.run([UMOUNT, S.ISOS], timeout=60, check=False).returncode != 0:
            log(f"{S.ISOS} is in use (a VM's CD?); the ISO share stays bound until it is free.")
            return
    rest = [e for e in entries if e["kind"] != "isos"]
    if wanted:
        os.makedirs(S.ISOS, exist_ok=True)
        for name in os.listdir(S.ISOS):                     # ISOs already in the library move into the share
            src = os.path.join(S.ISOS, name)
            dst = os.path.join(wanted, name)
            if not name.startswith(".") and os.path.isfile(src) and not os.path.islink(src) and not os.path.exists(dst):
                log(f"Moving {name} into the isos share")
                shutil.move(src, dst)
                os.chown(dst, -1, grp.getgrnam(GROUP).gr_gid)
                os.chmod(dst, 0o664)
        fsutil.write_block([*rest, {"kind": "isos", "source": wanted}], log)
        runner.run([MOUNT, S.ISOS], timeout=60)
        log(f"The isos share is now the VM ISO library ({S.ISOS})")
    else:
        fsutil.write_block(rest, log)


@REGISTRY.verb("share.apply", stream=True, lock="samba",
               args={"shares": Arg(S.share_list), "settings": Arg(S.samba_settings)})
def share_apply(ctx, args):
    shares, settings = args["shares"], args["settings"]
    ensure_include(ctx.log)
    availability = {}
    for s in shares:
        root, ok = location_root(s["location"])
        availability[s["name"]] = ok
        if ok:
            _ensure_dir(root, s["name"], ctx.log)
        else:
            ctx.log(f"{root} is not mounted: '{s['name']}' is published as unavailable until it is back.")
    new = {SETTINGS_CONF: render_settings(settings, shares), SHARES_CONF: render_shares(shares, availability)}
    with tempfile.TemporaryDirectory(prefix="nimbus-samba-") as tmp:
        _testparm(_candidate(tmp, new[SETTINGS_CONF], new[SHARES_CONF]), "the new configuration")
    old = {path: _read(path) for path in new}
    try:
        for path, content in new.items():
            os.makedirs(os.path.dirname(path), exist_ok=True)
            fsutil.write_atomic(path, content, 0o644)
        _reload()
        _testparm(SMB_CONF, SMB_CONF)
    except Exception:
        for path, content in old.items():
            if content is None:
                if os.path.exists(path):
                    os.unlink(path)
            else:
                fsutil.write_atomic(path, content, 0o644)
        try:
            _reload()
        except Exception:
            pass
        ctx.log("The previous Samba configuration was restored.")
        raise
    ctx.log(f"Samba now serves {sum(1 for s in shares if s['smb'])} share(s)")
    exported = [s for s in shares if s["smb"]]
    if exported and settings["enabled"]:
        if _read(AVAHI) != render_avahi(exported):
            os.makedirs(os.path.dirname(AVAHI), exist_ok=True)
            fsutil.write_atomic(AVAHI, render_avahi(exported), 0o644)
    else:
        fsutil.remove_if_marked(AVAHI, MARKER)
    _isos_bind(shares, ctx.log)
    return {"shares": len(shares), "exported": len(exported),
            "unavailable": sorted(n for n, ok in availability.items() if not ok)}


@REGISTRY.verb("share.delete_data", stream=True, lock="samba", args={
    "name": Arg(share_name), "location": Arg(S.location)})
def share_delete_data(ctx, args):
    root, ok = location_root(args["location"])
    if not ok:
        raise ValidationError("location", f"{root} is not mounted.")
    path = f"{root}/{args['name']}"
    exported = _read(SHARES_CONF) or ""
    if re.search(rf"^\s*path = {re.escape(path)}\s*$", exported, re.M):
        raise ValidationError("name", f"{path} is still shared. Delete the share first.")
    if path == S.ISOS or os.path.realpath(S.ISOS) == path:
        raise ValidationError("name", "The ISO library is still bound to this folder.")
    rfd = fsutil.open_dir(root)
    try:
        try:
            st = os.stat(args["name"], dir_fd=rfd, follow_symlinks=False)
        except FileNotFoundError:
            return {"deleted": None}
        if not stat.S_ISDIR(st.st_mode):
            raise ValidationError("name", f"{path} is not a folder; nothing was deleted.")
        ctx.log(f"Deleting {path}")
        shutil.rmtree(args["name"], dir_fd=rfd)
    finally:
        os.close(rfd)
    return {"deleted": path}


@REGISTRY.verb("samba.settings", lock="samba", args={"enabled": Arg(_bool), "netbios": Arg(_bool)})
def samba_settings(ctx, args):
    if not os.path.isdir("/run/systemd/system"):
        return {"applied": False, "reason": "systemd is not running"}
    on = ["smbd.service", "wsdd2.service"] + (["nmbd.service"] if args["netbios"] else [])
    off = ([] if args["enabled"] else ["smbd.service", "wsdd2.service"]) + \
        (["nmbd.service"] if not (args["enabled"] and args["netbios"]) else [])
    if args["enabled"]:
        runner.run([SYSTEMCTL, "enable", "--now", *on], timeout=120)
    if off:
        runner.run([SYSTEMCTL, "disable", "--now", *off], timeout=120)
    if not args["enabled"]:
        fsutil.remove_if_marked(AVAHI, MARKER)
    return {"applied": True, "enabled": args["enabled"], "netbios": args["netbios"]}


@REGISTRY.verb("samba.test", secret=("password",), args={"user": Arg(smb_user), "password": Arg(S.password)})
def samba_test(ctx, args):
    with tempfile.NamedTemporaryFile("w", prefix="nimbus-auth-", delete=True) as auth:
        os.fchmod(auth.fileno(), 0o600)
        auth.write(f"username = {args['user']}\npassword = {args['password']}\n")
        auth.flush()
        proc = runner.run([SMBCLIENT, "-L", "localhost", "-A", auth.name, "-g"], timeout=60, check=False)
    output = (proc.stdout + proc.stderr).strip()
    shares = [line.split("|")[1] for line in proc.stdout.splitlines() if line.startswith("Disk|")]
    if proc.returncode == 0:
        return {"ok": True, "shares": shares, "message": f"Connected as {args['user']}: {len(shares)} share(s) visible."}
    reason = "wrong user name or password" if "LOGON_FAILURE" in output else \
        "Samba isn't running (turn SMB on in Settings)" if "CONNECTION_REFUSED" in output else output.splitlines()[-1:]
    return {"ok": False, "shares": [], "message": f"Connecting failed: {reason if isinstance(reason, str) else ' '.join(reason)}."}


# --- SMB users -------------------------------------------------------------------------------------
def _registry():
    try:
        with open(REGISTRY_FILE, encoding="utf-8") as f:
            return set(json.load(f).get("users", []))
    except (OSError, ValueError):
        return set()


def _save_registry(users):
    os.makedirs(os.path.dirname(REGISTRY_FILE), mode=0o700, exist_ok=True)
    fsutil.write_atomic(REGISTRY_FILE, json.dumps({"users": sorted(users)}, indent=2) + "\n", 0o600)


def _samba_users():
    proc = runner.run([PDBEDIT, "-L"], timeout=30, check=False)
    return {line.split(":", 1)[0] for line in proc.stdout.splitlines() if ":" in line}


def _account(name):
    try:
        return pwd.getpwnam(name)
    except KeyError:
        return None


def _smbpasswd(args_, pw):
    runner.run([SMBPASSWD, *args_], input=f"{pw}\n{pw}\n", timeout=30)


@REGISTRY.verb("smbuser.list")
def smbuser_list(ctx, args):
    ours = _registry()
    out = []
    for name in sorted(_samba_users()):
        acct = _account(name)
        out.append({"name": name, "uid": acct.pw_uid if acct else None, "managed": name in ours,
                    "desktop": bool(acct and acct.pw_uid >= 1000 and name not in ours)})
    return {"users": out}


@REGISTRY.verb("smbuser.add", secret=("password",), lock="smbusers",
               args={"user": Arg(smb_user), "password": Arg(S.password)})
def smbuser_add(ctx, args):
    name = args["user"]
    if name in _samba_users():
        raise ValidationError("user", f"'{name}' is already an SMB user. Set a new password instead.")
    ours = _registry()
    acct = _account(name)
    created = False
    if acct is None:
        runner.run([ADDUSER, "--system", "--no-create-home", "--home", "/nonexistent", "--shell", "/usr/sbin/nologin",
                    "--ingroup", GROUP, "--comment", "NimbusOS SMB user", name], timeout=60)
        created = True
        ours.add(name)
        _save_registry(ours)
    elif name in ours:
        pass
    elif 1000 <= acct.pw_uid < 60000:
        runner.run([GPASSWD, "-a", name, GROUP], timeout=30)          # a desktop account: just join nimbus-smb
    else:
        raise ValidationError("user", f"'{name}' is a system account. Choose another name.")
    try:
        _smbpasswd(["-a", "-s", name], args["password"])
    except runner.CommandFailed:
        if created:
            runner.run([DELUSER, "--system", name], timeout=60, check=False)
            ours.discard(name)
            _save_registry(ours)
        raise
    return {"user": name, "created_account": created}


@REGISTRY.verb("smbuser.passwd", secret=("password",), lock="smbusers",
               args={"user": Arg(smb_user), "password": Arg(S.password)})
def smbuser_passwd(ctx, args):
    if args["user"] not in _samba_users():
        raise ValidationError("user", f"'{args['user']}' is not an SMB user.")
    _smbpasswd(["-s", args["user"]], args["password"])
    return {"user": args["user"]}


@REGISTRY.verb("smbuser.delete", lock="smbusers", args={"user": Arg(smb_user)})
def smbuser_delete(ctx, args):
    name = args["user"]
    if name not in _samba_users():
        raise ValidationError("user", f"'{name}' is not an SMB user.")
    runner.run([SMBPASSWD, "-x", name], timeout=30)
    ours = _registry()
    if name in ours:
        runner.run([DELUSER, "--system", name], timeout=60, check=False)
        ours.discard(name)
        _save_registry(ours)
    elif _account(name):
        runner.run([GPASSWD, "-d", name, GROUP], timeout=30, check=False)
    return {"user": name}
